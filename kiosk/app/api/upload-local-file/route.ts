import { NextRequest, NextResponse } from 'next/server'
import fs from 'fs'
import path from 'path'
import { localDb } from '@/lib/local-db'
import { assertLocalMutation } from '@/lib/local-request'

export const runtime = 'nodejs'

const MAX_BYTES = 200 * 1024 * 1024
const ALLOWED_EXT = new Set(['.mp4', '.webm', '.jpg', '.jpeg', '.png'])
const DENY_NAMES = new Set([
  'semeta.config.json',
  'license.json',
  'settings.json',
  'templates.json',
  'spindonesia.json',
  'seq.json',
])

function withinRoot(root: string, target: string): boolean {
  const rel = path.relative(root, target)
  return !!rel && !rel.startsWith('..') && !path.isAbsolute(rel)
}

/**
 * POST { local_path, type, session_id, event_name? }
 * Reads a file from the LOCAL DISK (C:/semeta/...) and uploads it to R2 via the Worker.
 * Designed for video _C.mp4 which is generated by FFmpeg locally — browser blob: URLs are
 * ephemeral and can't be relied on for upload. This route reads the actual file from disk,
 * bypassing the browser entirely.
 */
export async function POST(req: NextRequest) {
  try {
    assertLocalMutation(req)
  } catch (e) {
    return NextResponse.json({ error: e instanceof Error ? e.message : 'Ditolak' }, { status: 403 })
  }

  const workerUrl = process.env.NEXT_PUBLIC_WORKER_URL
  const secret = localDb.getSecret()
  if (!workerUrl || !secret)
    return NextResponse.json({ error: 'not configured' }, { status: 500 })

  const { local_path, type, session_id, event_name } = await req.json()
  if (typeof local_path !== 'string' || typeof type !== 'string' || typeof session_id !== 'string')
    return NextResponse.json({ error: 'local_path, type, session_id required' }, { status: 400 })

  // Security: hanya file MEDIA di bawah C:/semeta. Config/licence/settings DITOLAK
  // (dulu prefix C:/semeta/ doang → semeta.config.json berisi kiosk_secret bisa ke-upload).
  let root: string
  let resolved: string
  try {
    root = fs.realpathSync('C:/semeta')
    resolved = fs.realpathSync(path.resolve(local_path))
  } catch {
    return NextResponse.json({ error: 'file not found' }, { status: 404 })
  }
  if (!withinRoot(root, resolved))
    return NextResponse.json({ error: 'path must be under C:/semeta/' }, { status: 403 })
  if (DENY_NAMES.has(path.basename(resolved).toLowerCase()))
    return NextResponse.json({ error: 'file not allowed' }, { status: 403 })
  if (!ALLOWED_EXT.has(path.extname(resolved).toLowerCase()))
    return NextResponse.json({ error: 'file type not allowed' }, { status: 403 })

  const stat = fs.statSync(resolved)
  if (!stat.isFile() || stat.size > MAX_BYTES)
    return NextResponse.json({ error: 'file too large' }, { status: 413 })

  const buf = fs.readFileSync(resolved)
  const ext = path.extname(resolved).toLowerCase()
  const mime = ext === '.mp4' ? 'video/mp4' : ext === '.webm' ? 'video/webm' : 'image/jpeg'
  const blob = new Blob([buf], { type: mime })

  const form = new FormData()
  form.append('type', type)
  form.append('session_id', session_id)
  form.append('file', blob, path.basename(resolved))
  if (event_name) form.append('event_name', event_name)

  let res: Response
  try {
    res = await fetch(`${workerUrl}/api/upload`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${secret}` },
      body: form,
    })
  } catch (e) {
    const msg = e instanceof Error ? e.message : 'fetch failed'
    return NextResponse.json({ error: `worker unreachable: ${msg}` }, { status: 502 })
  }
  if (!res.ok) {
    const detail = await res.text().catch(() => '')
    console.error(`[upload-local-file] worker /api/upload ${res.status}: ${detail}`)
    return NextResponse.json(
      { error: 'upload failed', workerStatus: res.status, workerBody: detail.slice(0, 500) },
      { status: 502 },
    )
  }
  const data = await res.json()
  return NextResponse.json(data)
}
